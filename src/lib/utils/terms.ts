function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/**
 * يبني صفحة A4 (الظهر) بالشروط والأحكام كـ HTML جاهز للحقن في نافذة الطباعة.
 * يبدأ بـ page-break فيطلع كصفحة منفصلة (ظهر الإيصال عند الطباعة على الوجهين).
 */
export function renderTermsPageHtml(): string {
  const sections = TERMS_SECTIONS.map((s) => {
    const body = s.body ? `<p class="t-body">${esc(s.body)}</p>` : "";
    const items = s.items
      ? `<ul class="t-list">${s.items.map((i) => `<li>${esc(i)}</li>`).join("")}</ul>`
      : "";
    return `<section class="t-section">
      <h3 class="t-h"><span class="t-n">${esc(s.n)}.</span> ${esc(s.title)}</h3>
      ${body}${items}
    </section>`;
  }).join("");

  return `<div class="page terms" dir="rtl" lang="ar">
    <div class="t-header">
      <h2>${esc(TERMS_HEADER)}</h2>
      <h1>${esc(TERMS_TITLE)}</h1>
      <p class="t-intro">${esc(TERMS_INTRO)}</p>
    </div>
    <div class="t-body-wrap">${sections}</div>
    <div class="t-foot">بتسجيلك ودفعك للرسوم فأنت تقر بأنك اطّلعت على هذه الشروط والأحكام ووافقت عليها.</div>
  </div>`;
}

